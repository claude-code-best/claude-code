/** Clawd 像素吉祥物 — 仿官方 Claude Code 输入框上方的小机器人，纯装饰 */
export function ClawdPixel({ className, size = 36 }: { className?: string; size?: number }) {
  // 网格像素画：b=机身(brand) e=眼白 d=深色瞳孔
  const grid = [
    '..b.....b..',
    '..b.....b..',
    '.bbbbbbbbb.',
    '.beebbbeeb.',
    '.beebbbeeb.',
    '.bbbbbbbbb.',
    '..bbbbbbb..',
    '..b.b.b.b..',
  ];
  const cell = 4;
  const rects: React.ReactNode[] = [];
  grid.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const ch = row[x];
      if (ch === '.') continue;
      rects.push(
        <rect
          key={`${x}-${y}`}
          x={x * cell}
          y={y * cell}
          width={cell}
          height={cell}
          fill={ch === 'e' ? 'var(--color-surface-2)' : 'var(--color-brand)'}
        />,
      );
    }
  });
  return (
    <svg
      width={size}
      height={(size * 8) / 11}
      viewBox={`0 0 ${11 * cell} ${8 * cell}`}
      aria-hidden="true"
      className={cn('flex-shrink-0', className)}
    >
      {rects}
    </svg>
  );
}

/** 空会话占位像素图 — 仿 Claude Code 侧边栏空态的小像素簇 */
export function EmptySessionsGlyph({ className }: { className?: string }) {
  const cells = [
    [3, 0],
    [2, 1],
    [3, 1],
    [4, 1],
    [3, 2],
    [1, 3],
    [5, 3],
    [0, 4],
    [1, 4],
    [5, 4],
    [6, 4],
    [1, 5],
    [5, 5],
  ];
  const cell = 6;
  return (
    <svg
      width={7 * cell}
      height={6 * cell}
      viewBox={`0 0 ${7 * cell} ${6 * cell}`}
      aria-hidden="true"
      className={className}
    >
      {cells.map(([x, y]) => (
        <rect
          key={`${x}-${y}`}
          x={x * cell}
          y={y * cell}
          width={cell - 1}
          height={cell - 1}
          fill="var(--color-surface-3)"
        />
      ))}
    </svg>
  );
}
